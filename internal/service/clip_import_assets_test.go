func TestClipImageRejectsHeaderOnlyAndTrailingIDAT(t *testing.T) {
	for media, data := range clipTestImages(t) {
		for length := 1; length < len(data); length++ {
			r := bytes.NewReader(data[:length])
			err := preflightClipImage(t.Context(), r, int64(length), media)
			if err == nil {
				r.Seek(0, io.SeekStart)
				err = decodeClipImage(t.Context(), r, media)
			}
			if err == nil {
				t.Fatalf("accepted %s truncated at %d/%d", media, length, len(data))
			}
		}
	}
	data := clipTestImages(t)["image/png"]
	// Stdlib deliberately tolerates garbage IDAT after the first zlib stream.
	bad := append(append(append([]byte{}, data[:len(data)-12]...), clipPNGChunk("IDAT", []byte{1, 2, 3})...), data[len(data)-12:]...)
	requireClipError(t, preflightClipImage(t.Context(), bytes.NewReader(bad), int64(len(bad)), "image/png"), model.ClipperInvalidRequest)
}

type clipCancelReader struct {
	r      io.Reader
	cancel context.CancelFunc
}

func (r *clipCancelReader) Read(p []byte) (int, error) {
	n, err := r.r.Read(p)
	r.cancel()
	return n, err
}
func TestStagedClipCancellationCleansFiles(t *testing.T) {
	data := clipTestImages(t)["image/png"]
	part := clipTestPart{"a", "image/png", data}
	m := validClipManifest()
	m.Assets = []model.ClipperAsset{clipDescriptor(part)}
	var wire bytes.Buffer
	w := multipart.NewWriter(&wire)
	p, _ := w.CreatePart(textproto.MIMEHeader{"Content-Disposition": {`form-data; name="a"`}, "Content-Type": {"image/png"}})
	p.Write(data)
	w.Close()
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	root, _ := os.OpenRoot(t.TempDir())
	defer root.Close()
	_, err := StageClip(ctx, root, multipart.NewReader(&clipCancelReader{bytes.NewReader(wire.Bytes()), cancel}, w.Boundary()))
	if !errors.Is(err, context.Canceled) {
		t.Fatal(err)
	}
	dir, _ := root.Open(".")
	defer dir.Close()
	names, _ := dir.Readdirnames(-1)
	if len(names) != 0 {
		t.Fatal(names)
	}
}

func TestClipGIFCorruptLaterFrame(t *testing.T) {
	frame := image.NewPaletted(image.Rect(0, 0, 2, 2), color.Palette{color.Black, color.White})
	var b bytes.Buffer
	gif.EncodeAll(&b, &gif.GIF{Image: []*image.Paletted{frame, frame}, Delay: []int{0, 0}})
	data := b.Bytes()
	second := bytes.LastIndex(data, []byte{0x2c, 0, 0, 0, 0, 2, 0, 2, 0})
	if second < 0 {
		t.Fatal("missing second descriptor")
	}
	// The encoded palette may use an 8-bit minimum code size. Fill the whole
	// compressed sub-block with out-of-dictionary codes, keeping its framing.
	start := second + 10
	if data[second+9]&0x80 != 0 {
		start += 3 * (1 << ((data[second+9] & 7) + 1))
	}
	for i := start + 2; i < start+2+int(data[start+1]); i++ {
		data[i] = 0xff
	}
	if err := preflightClipGIF(&clipImageCursor{ctx: t.Context(), r: bytes.NewReader(data), size: int64(len(data))}); err != nil {
		t.Fatalf("test must reach full decode: %v", err)
	}
	requireClipError(t, decodeClipImage(t.Context(), bytes.NewReader(data), "image/gif"), model.ClipperInvalidRequest)
}
