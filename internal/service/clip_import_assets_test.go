func TestClipDecodeGateCancellation(t *testing.T) {
	clipDecodeGate <- struct{}{}
	defer func() { <-clipDecodeGate }()
	ctx, cancel := context.WithCancel(t.Context())
	defer cancel()
	data := clipTestImages(t)["image/png"]
	started := make(chan struct{})
	done := make(chan error, 1)
	go func() { close(started); done <- decodeClipImage(ctx, bytes.NewReader(data), "image/png") }()
	<-started
	select {
	case err := <-done:
		t.Fatalf("decoder bypassed held process gate: %v", err)
	default:
	}
	cancel()
	select {
	case err := <-done:
		if err != context.Canceled {
			t.Fatal(err)
		}
	case <-time.After(5 * time.Second):
		t.Fatal("waiting decoder ignored cancellation")
	}
}

func TestClipGIFPreflightPixelBudgetsWithoutAllocation(t *testing.T) {
	build := func(w, h uint16, frames int) []byte {
		var b bytes.Buffer
		b.WriteString("GIF89a")
		binary.Write(&b, binary.LittleEndian, w)
		binary.Write(&b, binary.LittleEndian, h)
		b.Write([]byte{0x80, 0, 0, 0, 0, 0, 255, 255, 255})
		for range frames {
			b.Write([]byte{0x2c, 0, 0, 0, 0})
			binary.Write(&b, binary.LittleEndian, w)
			binary.Write(&b, binary.LittleEndian, h)
			b.Write([]byte{0, 2, 2, 0x44, 1, 0})
		}
		b.WriteByte(0x3b)
		return b.Bytes()
	}
	for _, tc := range []struct {
		w, h   uint16
		frames int
		ok     bool
	}{{8000, 5000, 1, true}, {8001, 5000, 1, false}, {8000, 5000, 5, true}, {8000, 5000, 6, false}, {2, 2, 100, true}, {2, 2, 101, false}} {
		data := build(tc.w, tc.h, tc.frames)
		err := preflightClipGIF(&clipImageCursor{ctx: t.Context(), r: bytes.NewReader(data), size: int64(len(data))})
		if tc.ok {
			if err != nil {
				t.Fatal(tc, err)
			}
		} else {
			requireClipError(t, err, model.ClipperTooLarge)
		}
	}
}

