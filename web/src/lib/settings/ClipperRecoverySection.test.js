import { render, screen, within, fireEvent, waitFor } from '@testing-library/svelte'
import userEvent from '@testing-library/user-event'
import { tick } from 'svelte'
import { beforeEach, expect, it, vi } from 'vitest'
vi.mock('../api.js', () => ({ getClipperImports: vi.fn(), abandonClipperImport: vi.fn() }))
import { getClipperImports, abandonClipperImport } from '../api.js'
import ClipperRecoverySection from './ClipperRecoverySection.svelte'

const row = { import_id: '12345678-1234-4123-8123-123456789abc', base: 'Notes', path: 'nested/note.md', state: 'recovery_required', error: { code: 'clipper_recovery_required', message: 'Clipper import requires recovery' } }
function deferred() { let resolve, reject; const promise = new Promise((yes, no) => { resolve = yes; reject = no }); return { promise, resolve, reject } }
beforeEach(() => {
  vi.mocked(getClipperImports).mockReset().mockResolvedValue({ imports: [row] })
  vi.mocked(abandonClipperImport).mockReset().mockResolvedValue({ import_id: row.import_id, state: 'rejected', error: { code: 'clipper_import_abandoned', message: 'Clipper import abandoned; files may already exist' } })
})
it('loads summaries, distinguishes pending and only offers abandonment for recovery', async () => {
  getClipperImports.mockResolvedValue({ imports: [row, { ...row, import_id: 'pending-id', state: 'pending', error: undefined }] })
  render(ClipperRecoverySection)
  expect(screen.getByRole('status')).toHaveTextContent('Загрузка незавершённых импортов')
  expect(await screen.findAllByText(row.path)).toHaveLength(2)
  expect(screen.getAllByText(row.base)).toHaveLength(2)
  expect(screen.getByText(row.import_id)).toBeVisible()
  expect(screen.getByText('Выполняется')).toBeVisible()
  expect(screen.getAllByRole('button', { name: 'Прекратить попытку' })).toHaveLength(1)
  expect(abandonClipperImport).not.toHaveBeenCalled()
})
it('requires explicit confirmation, supports keyboard cancel and refetches after confirmation', async () => {
  const user = userEvent.setup(); render(ClipperRecoverySection)
  const action = await screen.findByRole('button', { name: 'Прекратить попытку' })
  await user.click(action)
  let dialog = screen.getByRole('dialog')
  expect(dialog).toHaveTextContent('Файлы могут уже существовать')
  expect(dialog).toHaveTextContent('не удаляет')
  expect(dialog).toHaveTextContent(row.import_id)
  expect(abandonClipperImport).not.toHaveBeenCalled()
  await waitFor(() => expect(within(dialog).getByRole('button', { name: 'Подтвердить прекращение' })).toHaveFocus())
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(action).toHaveFocus()
  await user.click(action)
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Отмена' }))
  expect(abandonClipperImport).not.toHaveBeenCalled()
  await user.click(action)
  getClipperImports.mockResolvedValue({ imports: [] })
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Подтвердить прекращение' }))
  expect(abandonClipperImport).toHaveBeenCalledExactlyOnceWith(row.import_id)
  expect(await screen.findByText('Незавершённых импортов нет')).toBeVisible()
  expect(screen.getByText(/Попытка прекращена/)).toHaveTextContent('Файлы могут уже существовать')
  expect(getClipperImports).toHaveBeenCalledTimes(2)
  await waitFor(() => expect(screen.getByRole('heading', { name: 'Незавершённые импорты' })).toHaveFocus())
})
it('retries GET manually and keeps failed abandon explicit and single-flight', async () => {
  const user = userEvent.setup()
  getClipperImports.mockRejectedValueOnce(new Error('List offline'))
  render(ClipperRecoverySection)
  expect(await screen.findByRole('alert')).toHaveTextContent('List offline')
  await user.click(screen.getByRole('button', { name: 'Повторить загрузку импортов' }))
  await user.click(await screen.findByRole('button', { name: 'Прекратить попытку' }))
  const pending = deferred(); abandonClipperImport.mockReturnValueOnce(pending.promise)
  const confirm = within(screen.getByRole('dialog')).getByRole('button', { name: 'Подтвердить прекращение' })
  await user.click(confirm); expect(confirm).toBeDisabled(); await fireEvent.click(confirm)
  expect(abandonClipperImport).toHaveBeenCalledOnce()
  pending.reject(new Error('Abandon offline'))
  expect(await screen.findByRole('alert')).toHaveTextContent('Abandon offline')
  expect(abandonClipperImport).toHaveBeenCalledOnce()
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Отмена' }))
  await user.click(screen.getByRole('button', { name: 'Обновить импорты' }))
  expect(getClipperImports).toHaveBeenCalledTimes(3)
})
it('keeps confirmed abandonment authoritative through failed refresh and later stale snapshots', async () => {
  const user = userEvent.setup()
  const other = { ...row, import_id: '22345678-1234-4123-8123-123456789abc', path: 'nested/other.md' }
  getClipperImports.mockResolvedValueOnce({ imports: [row, other] })
  const refresh = deferred()
  getClipperImports.mockReturnValueOnce(refresh.promise)
  render(ClipperRecoverySection)
  const confirmedCard = await screen.findByRole('article', { name: `Импорт ${row.import_id}` })
  await user.click(within(confirmedCard).getByRole('button', { name: 'Прекратить попытку' }))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Подтвердить прекращение' }))
  expect(await screen.findByText(/Попытка прекращена/)).toHaveTextContent(row.import_id)
  // Remove the confirmed row before the metadata request has any outcome.
  expect(screen.queryByRole('article', { name: `Импорт ${row.import_id}` })).not.toBeInTheDocument()
  refresh.reject(new Error('Refresh offline'))
  expect(await screen.findByRole('alert')).toHaveTextContent('Refresh offline')
  expect(screen.getByText(/Попытка прекращена/)).toHaveTextContent('Файлы могут уже существовать')
  expect(screen.queryByRole('article', { name: `Импорт ${row.import_id}` })).not.toBeInTheDocument()
  const otherCard = screen.getByRole('article', { name: `Импорт ${other.import_id}` })
  expect(within(otherCard).getByRole('button', { name: 'Прекратить попытку' })).toBeEnabled()
  await user.click(within(otherCard).getByRole('button', { name: 'Прекратить попытку' }))
  expect(screen.getByRole('dialog')).toHaveTextContent(other.import_id)
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Отмена' }))
  // A stale snapshot must not resurrect a terminal ID; new IDs remain actionable.
  const newAttempt = { ...row, import_id: '32345678-1234-4123-8123-123456789abc' }
  getClipperImports.mockResolvedValueOnce({ imports: [row, other, newAttempt] })
  await user.click(screen.getByRole('button', { name: 'Повторить загрузку импортов' }))
  expect(await screen.findByRole('article', { name: `Импорт ${newAttempt.import_id}` })).toBeVisible()
  expect(screen.queryByRole('article', { name: `Импорт ${row.import_id}` })).not.toBeInTheDocument()
  expect(screen.getAllByRole('button', { name: 'Прекратить попытку' })).toHaveLength(2)
  expect(abandonClipperImport).toHaveBeenCalledExactlyOnceWith(row.import_id)
})
it.each(['resolve', 'reject'])('does not move focus on late refresh %s after successful abandon and unmount', async (settlement) => {
  const user = userEvent.setup()
  const refresh = deferred()
  getClipperImports.mockResolvedValueOnce({ imports: [row] }).mockReturnValueOnce(refresh.promise)
  const result = render(ClipperRecoverySection)
  await user.click(await screen.findByRole('button', { name: 'Прекратить попытку' }))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Подтвердить прекращение' }))
  await waitFor(() => expect(screen.getByRole('heading', { name: 'Незавершённые импорты' })).toHaveFocus())
  result.unmount()
  const focus = vi.spyOn(HTMLElement.prototype, 'focus')
  try {
    if (settlement === 'resolve') refresh.resolve({ imports: [row] }); else refresh.reject(new Error('Late refresh'))
    await refresh.promise.catch(() => {}); await tick()
    expect(focus).not.toHaveBeenCalled()
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(getClipperImports).toHaveBeenCalledTimes(2)
  } finally { focus.mockRestore() }
})
it.each(['resolve', 'reject'])('ignores late list %s after unmount', async (settlement) => {
  const pending = deferred(); getClipperImports.mockReturnValueOnce(pending.promise)
  const result = render(ClipperRecoverySection); result.unmount()
  if (settlement === 'resolve') pending.resolve({ imports: [row] }); else pending.reject(new Error('Late error'))
  await pending.promise.catch(() => {}); await tick()
  expect(document.body).not.toHaveTextContent(row.import_id)
  expect(abandonClipperImport).not.toHaveBeenCalled()
})
it.each(['resolve', 'reject'])('ignores late abandon %s without refetch after unmount', async (settlement) => {
  const user = userEvent.setup(); const pending = deferred(); abandonClipperImport.mockReturnValueOnce(pending.promise)
  const result = render(ClipperRecoverySection)
  await user.click(await screen.findByRole('button', { name: 'Прекратить попытку' }))
  await user.click(within(screen.getByRole('dialog')).getByRole('button', { name: 'Подтвердить прекращение' }))
  result.unmount()
  if (settlement === 'resolve') pending.resolve({}); else pending.reject(new Error('Late error'))
  await pending.promise.catch(() => {}); await tick()
  expect(getClipperImports).toHaveBeenCalledOnce()
  expect(screen.queryByRole('alert')).not.toBeInTheDocument()
})
